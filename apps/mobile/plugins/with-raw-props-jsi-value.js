const { withMainApplication } = require('expo/config-plugins');

// vision-camera 5.2 hands its outputs to the native PreviewView as raw JSI values. Without the
// React Native feature flag `useRawPropsJsiValue` the `previewOutput` prop throws
// ("Cannot cast dynamic to a jsi::Value type"), the ErrorBoundary around the camera catches it
// and the scanner silently falls back to expo-camera - no live detection, no error visible to
// anyone.
//
// The flag has no gradle.properties or app.json equivalent, it has to be set in code. By the
// time MainApplication runs, loadReactNative has already applied the stable flag set, and
// overriding twice throws, so the only way in is dangerouslyForceOverride. It delegates to the
// stable set and changes the single flag, which keeps the new architecture flags intact.
//
// This lives in a config plugin rather than in android/: that directory is generated by
// expo prebuild and is not in the repository, so an edit there would disappear on the next
// prebuild and take the live scanner with it.

const IMPORTS = [
  'import com.facebook.react.internal.featureflags.ReactNativeFeatureFlags',
  'import com.facebook.react.internal.featureflags.ReactNativeFeatureFlagsOverrides_RNOSS_Stable_Android',
  'import com.facebook.react.internal.featureflags.ReactNativeFeatureFlagsProvider',
];

const OVERRIDE = `    // See plugins/with-raw-props-jsi-value.js - required by vision-camera 5.2.
    val stableFeatureFlags = ReactNativeFeatureFlagsOverrides_RNOSS_Stable_Android(true, true, true)
    ReactNativeFeatureFlags.dangerouslyForceOverride(
      object : ReactNativeFeatureFlagsProvider by stableFeatureFlags {
        override fun useRawPropsJsiValue(): Boolean = true
      }
    )`;

const ANCHOR = '    loadReactNative(this)';

const withRawPropsJsiValue = (config) =>
  withMainApplication(config, (mod) => {
    let contents = mod.modResults.contents;

    if (contents.includes('useRawPropsJsiValue')) {
      return mod;
    }
    if (!contents.includes(ANCHOR)) {
      throw new Error(
        'with-raw-props-jsi-value: could not find "loadReactNative(this)" in MainApplication. ' +
          'The React Native entry point changed; the feature flag override needs a new anchor.',
      );
    }

    const lastImport = contents.lastIndexOf('\nimport ');
    const endOfImports = contents.indexOf('\n', lastImport + 1);
    contents =
      contents.slice(0, endOfImports) + '\n' + IMPORTS.join('\n') + contents.slice(endOfImports);

    // After loadReactNative, because the override reaches into native code that it loads.
    contents = contents.replace(ANCHOR, `${ANCHOR}\n${OVERRIDE}`);

    mod.modResults.contents = contents;
    return mod;
  });

module.exports = withRawPropsJsiValue;
